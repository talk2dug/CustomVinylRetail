// DESIGN GENERATION (uses Gemini AI workflow)
// =============================================================================

const PRINT_METHOD_INSTRUCTIONS = {
  dtf: 'full color design, suitable for DTF print transfer, vibrant colors, transparent or solid background, no mockup',
  vinyl: 'bold single or dual-color design, suitable for vinyl heat transfer, clean lines, solid fills, vector-style, no gradients',
  sublimation: 'all-over print design, edge-to-edge coverage, vibrant full-color, sublimation ready, seamless pattern elements'
};

function buildApparelPrompt(phrase, visualConcept, printMethod) {
  const method = PRINT_METHOD_INSTRUCTIONS[printMethod] || PRINT_METHOD_INSTRUCTIONS.dtf;
  return `T-shirt graphic design: "${phrase}". ${visualConcept}. ${method}. Isolated design only, print-ready, high contrast, bold typography, no human models, no clothing mockup`;
}

async function generateDesignForTrend(trend, settings) {
  const { NanoBananaWorkflow, MODELS } = require('../nano-banana-workflow');
  const workflow = new NanoBananaWorkflow();
  const designs = [];

  const phrases = (trend.aiAnalysis.suggestedPhrases || []).slice(0, 2);
  const visual = (trend.aiAnalysis.suggestedVisuals || [])[0] || 'bold retro typography with distressed texture';
  const printMethod = trend.aiAnalysis.printMethodRecommendation || 'dtf';

  for (const phrase of phrases) {
    if (!passesContentFilter(phrase, settings)) continue;

    const promptKeywords = buildApparelPrompt(phrase, visual, printMethod);

    try {
      const result = await workflow.runWithPrompt(promptKeywords, {
        aspectRatio: '1:1',
        numImages: 2,
        model: MODELS.GEMINI_2_FLASH,
        category: 'products/apparel',
        addToArtwork: false
      });

      if (result.success && result.images) {
        for (const image of result.images) {
          designs.push({
            id: `design_${crypto.randomUUID().slice(0, 12)}`,
            trendId: trend.id,
            phrase,
            visualDescription: visual,
            aiPrompt: promptKeywords,
            aiGenerationId: image.generationId || null,
            imagePath: `/images/ai-generated/text-to-image/${image.filename}`,
            imageFilename: image.filename,
            imageUrl: image.url || null,
            status: 'pending',
            printMethod,
            shopifyProductId: null,
            shopifyProductUrl: null,
            createdAt: new Date().toISOString(),
            approvedAt: null,
            listedAt: null,
            listingData: null
          });
        }
      }
    } catch (err) {
      console.error(`[TrendMonitor] Design generation failed for "${phrase}":`, err.message);
    }
  }

  return designs;
}

