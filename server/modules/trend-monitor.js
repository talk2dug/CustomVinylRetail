// TREND SCORING ALGORITHM
// =============================================================================

const SCORE_WEIGHTS = {
  virality: 0.20,
  humorPotential: 0.30,
  apparelRelevance: 0.25,
  audienceMatch: 0.15,
  timeliness: 0.10
};

function calculateCompositeScore(breakdown) {
  let score = 0;
  for (const [key, weight] of Object.entries(SCORE_WEIGHTS)) {
    score += (breakdown[key] || 0) * weight;
  }
  return Math.round(score);
}

