async function analyzeTrendsWithClaude(rawTrends, settings) {
  if (!rawTrends.length) return [];

  const systemPrompt = `You are a trend-to-apparel design analyst for a print-on-demand business.
Evaluate social media trends for sarcastic/witty/comical t-shirt design potential.
Target: GenX, Millennials, GenZ. Style: ${settings.designStyle}.
Print: DTF (full color), Vinyl (solid colors, text), Sublimation (all-over).
Rules: BLOCK sexual assault references. Edgy/political/dark humor OK.

ONLY return items that WOULD make good apparel. Skip the rest entirely.

For each good trend return a JSON object:
{"originalTitle":"...","isGoodForApparel":true,"scoreBreakdown":{"virality":0-100,"humorPotential":0-100,"apparelRelevance":0-100,"audienceMatch":0-100,"timeliness":0-100},"reasoning":"1 sentence","suggestedPhrases":["phrase1","phrase2"],"suggestedVisuals":["visual desc"],"targetAudience":"genx|millennial|genz|all","humorStyle":"sarcastic|witty|absurdist|deadpan|nostalgic|self-deprecating","printMethodRecommendation":"dtf|vinyl|sublimation"}

Return ONLY a JSON array. No markdown fences, no explanation, no text outside the array.`;

  // Process in batches of 15 to avoid token limits
  const BATCH_SIZE = 15;
  const allAnalyzed = [];
  const trendsToAnalyze = rawTrends.slice(0, 60); // Cap at 60 total

  for (let i = 0; i < trendsToAnalyze.length; i += BATCH_SIZE) {
    const batch = trendsToAnalyze.slice(i, i + BATCH_SIZE);
    const batchData = batch.map(t => ({
      title: t.title.slice(0, 150),
      source: t.source,
      snippet: (t.snippet || '').slice(0, 100),
      subreddit: t.subreddit || null
    }));

    try {
      const batchNum = Math.floor(i / BATCH_SIZE) + 1;
      const totalBatches = Math.ceil(trendsToAnalyze.length / BATCH_SIZE);
      console.log(`[TrendMonitor] Ollama batch ${batchNum}/${totalBatches} (${batchData.length} trends)...`);

      const messages = [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: `Evaluate these ${batchData.length} trends. Only return the ones good for t-shirts:\n${JSON.stringify(batchData)}` }
      ];

      const text = await ollamaClient.chat(messages, { temperature: 0.5, timeout: 180000 });
      const cleaned = text.replace(/^```json?\s*/i, '').replace(/```\s*$/i, '').trim();
      const results = JSON.parse(cleaned);

      if (!Array.isArray(results)) continue;

      // Merge results back into raw trends
      for (const raw of batch) {
        const match = results.find(r =>
          r.originalTitle === raw.title ||
          r.originalTitle?.toLowerCase() === raw.title?.toLowerCase() ||
          raw.title?.toLowerCase().includes((r.originalTitle || '').toLowerCase().slice(0, 40))
        );

        if (match && match.isGoodForApparel) {
          const scoreBreakdown = match.scoreBreakdown || {};
          allAnalyzed.push({
            ...raw,
            score: calculateCompositeScore(scoreBreakdown),
            scoreBreakdown,
            aiAnalysis: {
              isGoodForApparel: true,
              reasoning: match.reasoning || '',
              suggestedPhrases: match.suggestedPhrases || [],
              suggestedVisuals: match.suggestedVisuals || [],
              targetAudience: match.targetAudience || 'all',
              humorStyle: match.humorStyle || 'witty',
              printMethodRecommendation: match.printMethodRecommendation || 'dtf'
            },
            status: 'new',
            discoveredAt: new Date().toISOString(),
            expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString()
          });
        }
      }
    } catch (err) {
      console.error(`[TrendMonitor] Ollama batch ${Math.floor(i / BATCH_SIZE) + 1} error:`, err.message);
    }
  }

  console.log(`[TrendMonitor] Ollama analysis complete: ${allAnalyzed.length} trends qualify for apparel`);
  return allAnalyzed;
}

