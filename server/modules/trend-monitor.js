/**
 * Determine if a product should be published to TikTok Shop based on capacity and type.
 * @param {string} productType - e.g. 'T-Shirt', 'Metal Print', 'Multiboard'
 * @param {object} capacity - { current, max, available }
 * @returns {{ publish: boolean, reason: string }}
 */
function shouldPublishToTikTok(productType, capacity) {
  if (!capacity || capacity.available <= 0) {
    return { publish: false, reason: `TikTok Shop full (${capacity?.current || '?'}/${capacity?.max || 100})` };
  }

  const type = (productType || '').toLowerCase();
  const preferred = ['metal print', 'metal art', 'multiboard', 'wall organizer'];
  const acceptable = ['t-shirt', 'tshirt'];

  const isPreferred = preferred.some(p => type.includes(p));
  const isAcceptable = acceptable.some(a => type.includes(a));

  // Always publish preferred categories
  if (isPreferred) {
    return { publish: true, reason: `Preferred category for TikTok (${capacity.current}/${capacity.max})` };
  }

  // Publish acceptable categories if there's decent room (>10 slots)
  if (isAcceptable && capacity.available > 10) {
    return { publish: true, reason: `Acceptable category, room available (${capacity.current}/${capacity.max})` };
  }

  // Trending t-shirts get in if there's room (>20 slots)
  if (isAcceptable && capacity.available > 20) {
    return { publish: true, reason: `Trending tee, good capacity (${capacity.current}/${capacity.max})` };
  }

  return { publish: false, reason: `Category not prioritized for TikTok or low capacity (${capacity.current}/${capacity.max})` };
}

// SHOPIFY AUTO-LISTING (uses existing Shopify + listing optimizer)
// =============================================================================

async function listDesignToShopify(design, trend, settings) {
  const shopify = require('../integrations/shopify');

  if (!shopify.isConfigured()) {
    throw new Error('Shopify not configured');
  }

  const basePriceDollars = (settings.defaultPriceCents / 100).toFixed(2);
  const xlPrice = ((settings.defaultPriceCents + 200) / 100).toFixed(2);
  const xxlPrice = ((settings.defaultPriceCents + 400) / 100).toFixed(2);

  const tags = [
    'trending', 'trend-monitor', 'auto-generated',
    trend.aiAnalysis?.targetAudience || 'all',
    trend.aiAnalysis?.humorStyle || 'witty',
    design.printMethod || 'dtf'
  ].join(', ');

  const descriptionHtml = `<p>${design.phrase}</p>
<p><strong>Style:</strong> ${trend.aiAnalysis?.humorStyle || 'witty'} humor</p>
<ul>
<li>Premium quality ${design.printMethod?.toUpperCase() || 'DTF'} print</li>
<li>Available in sizes S-2XL</li>
<li>Machine washable</li>
<li>Unisex fit</li>
</ul>
<p><em>Inspired by what's trending right now.</em></p>`;

  const product = {
    title: design.phrase.slice(0, 255),
    body_html: descriptionHtml,
    tags,
    product_type: 'T-Shirt',
    vendor: 'BlueRidgeCustomCo',
    variants: [
      { option1: 'S', price: basePriceDollars, sku: `TREND-${design.id}-S`, inventory_management: null },
      { option1: 'M', price: basePriceDollars, sku: `TREND-${design.id}-M`, inventory_management: null },
      { option1: 'L', price: basePriceDollars, sku: `TREND-${design.id}-L`, inventory_management: null },
      { option1: 'XL', price: xlPrice, sku: `TREND-${design.id}-XL`, inventory_management: null },
      { option1: '2XL', price: xxlPrice, sku: `TREND-${design.id}-2XL`, inventory_management: null }
    ],
    options: [{ name: 'Size', values: ['S', 'M', 'L', 'XL', '2XL'] }],
    status: 'active'
  };

  // Create the product
  const created = await shopify.createProduct(product);
  console.log(`[TrendMonitor] Shopify product created: ${created.id}`);

  // Add the design image
  const imagePath = path.join(__dirname, '..', '..', 'web', design.imagePath);
  if (fs.existsSync(imagePath)) {
    const imageBase64 = fs.readFileSync(imagePath).toString('base64');
    await shopify.addProductImage(created.id, {
      attachment: imageBase64,
      filename: design.imageFilename,
      alt: design.phrase
    });
  } else if (design.imageUrl) {
    await shopify.addProductImage(created.id, {
      src: design.imageUrl,
      alt: design.phrase
    });
  }

  // Find or create the trending collection
  let collection = await shopify.findCustomCollectionByTitle(settings.shopifyCollectionTitle);
  if (!collection) {
    collection = await shopify.createCustomCollection(settings.shopifyCollectionTitle, {
      body_html: '<p>Hot trending designs fresh from social media. Limited availability!</p>'
    });
    console.log(`[TrendMonitor] Created Shopify collection: ${settings.shopifyCollectionTitle}`);
  }

  if (collection?.id) {
    await shopify.addProductToCollection(created.id, collection.id);
  }

  // Publish to sales channels — with TikTok capacity awareness
  try {
    // First, publish to all channels
    await shopify.publishEverywhere(created.id);

    // Then check TikTok capacity and unpublish if needed
    const tiktokPub = await shopify.findTikTokPublication();
    if (tiktokPub) {
      const tiktokProducts = await shopify.getProductsOnPublication(tiktokPub.id);
      const capacity = { current: tiktokProducts.length, max: 100, available: Math.max(0, 100 - tiktokProducts.length) };
      const tiktokDecision = shouldPublishToTikTok(product.product_type, capacity);

      if (!tiktokDecision.publish) {
        await shopify.unpublishFromPublication(created.id, [tiktokPub.id]);
        console.log(`[TrendMonitor] TikTok Shop at ${capacity.current}/100 — skipped: ${tiktokDecision.reason}`);
      } else {
        console.log(`[TrendMonitor] TikTok Shop at ${capacity.current}/100 — published: ${tiktokDecision.reason}`);
      }
    }
  } catch (err) {
    console.error('[TrendMonitor] Publish error (non-fatal):', err.message);
  }

  return {
    shopifyProductId: created.id,
    shopifyProductUrl: created.handle
      ? `https://${process.env.SHOPIFY_STORE_DOMAIN || 'store'}/products/${created.handle}`
      : null
  };
}

