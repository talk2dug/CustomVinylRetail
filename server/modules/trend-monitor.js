let _scanRunning = false;

async function runTrendScan(settings) {
  if (_scanRunning) {
    console.log('[TrendMonitor] Scan already in progress, skipping');
    return [];
  }
  _scanRunning = true;

  console.log('[TrendMonitor] Starting trend scan...');
  const scanStart = Date.now();

  try {
    // Step 1: Fetch raw trends
    console.log('[TrendMonitor] Fetching Reddit trends...');
    const redditTrends = await fetchRedditTrends(
      settings.redditSubreddits || DEFAULT_SETTINGS.redditSubreddits,
      settings.maxTrendsPerScan || 20
    );
    console.log(`[TrendMonitor] Reddit: ${redditTrends.length} posts found`);

    console.log('[TrendMonitor] Fetching Google Trends...');
    const googleTrendResults = await fetchGoogleTrends(settings.googleTrendsGeo || 'US');
    console.log(`[TrendMonitor] Google: ${googleTrendResults.length} trends found`);

    // Step 2: Merge and deduplicate
    const allRaw = deduplicateTrends([...redditTrends, ...googleTrendResults]);
    console.log(`[TrendMonitor] ${allRaw.length} unique trends after dedup`);

    if (allRaw.length === 0) {
      console.log('[TrendMonitor] No trends found this scan');
      _scanRunning = false;
      return [];
    }

    // Step 3: Claude AI analysis and scoring
    console.log('[TrendMonitor] Analyzing trends with Claude...');
    const analyzed = await analyzeTrendsWithClaude(allRaw, settings);
    console.log(`[TrendMonitor] ${analyzed.length} trends scored above design threshold`);

    // Step 4: Filter content
    const filtered = analyzed.filter(t =>
      passesContentFilter(t.title + ' ' + (t.aiAnalysis?.suggestedPhrases || []).join(' '), settings)
    );

    // Step 5: Save trends to data store (merge with existing, avoid duplicates)
    const data = loadData();
    const existingIds = new Set(data.trends.map(t => t.id));
    let newCount = 0;

    for (const trend of filtered) {
      if (!existingIds.has(trend.id)) {
        data.trends.push(trend);
        existingIds.add(trend.id);
        newCount++;
      }
    }

    // Step 6: Generate designs for high-scoring new trends
    if (settings.autoGenerateDesigns) {
      const designTrends = filtered.filter(t => t.score >= (settings.minScoreForDesign || 65));
      console.log(`[TrendMonitor] Generating designs for ${designTrends.length} trend(s)...`);

      for (const trend of designTrends) {
        // Auto-generation disabled — costs too much on Gemini API.
        // Trends are still tracked; designs can be generated manually from the UI.
        // Skip if designs already exist for this trend
        if (data.designs.some(d => d.trendId === trend.id)) continue;
        console.log(`[TrendMonitor] Trend logged (no auto-generate): ${trend.title.slice(0, 60)}`);
      }
    }

    // Step 7: Send alerts for high-scoring trends
    const alertTrends = filtered.filter(t => t.score >= (settings.minScoreForAlert || 80));
    if (alertTrends.length > 0) {
      await sendTrendAlerts(alertTrends, settings);
    }

    // Step 8: Update stats and save
    data.lastScanAt = new Date().toISOString();
    data.scanCount++;
    data.stats.totalScans++;
    data.stats.totalTrendsFound += newCount;
    saveData(data);

    const elapsed = ((Date.now() - scanStart) / 1000).toFixed(1);
    console.log(`[TrendMonitor] Scan complete: ${newCount} new trends, ${filtered.length} total qualifying, ${elapsed}s elapsed`);

    return filtered;
  } catch (err) {
    console.error('[TrendMonitor] Scan error:', err.message);
    return [];
  } finally {
    _scanRunning = false;
  }
}

function deduplicateTrends(trends) {
  const seen = new Set();
  return trends.filter(t => {
    const key = t.title.toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 60);
    if (seen.has(key) || seen.has(t.id)) return false;
    seen.add(key);
    seen.add(t.id);
    return true;
  });
}

