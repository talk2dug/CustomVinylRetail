function archiveTrend(trendId) {
  const data = loadData();
  const idx = data.trends.findIndex(t => t.id === trendId);
  if (idx < 0) return false;

  const trend = data.trends.splice(idx, 1)[0];
  trend.status = 'archived';

  const history = loadHistory();
  history.archivedTrends.push(trend);
  // Keep last 500 archived trends
  if (history.archivedTrends.length > 500) {
    history.archivedTrends = history.archivedTrends.slice(-500);
  }
  saveHistory(history);
  saveData(data);
  return true;
}

function approveDesign(designId) {
  const data = loadData();
  const design = data.designs.find(d => d.id === designId);
  if (!design) return null;

  design.status = 'approved';
  design.approvedAt = new Date().toISOString();
  data.stats.totalApproved++;
  saveData(data);
  return design;
}

function rejectDesign(designId) {
  const data = loadData();
  const design = data.designs.find(d => d.id === designId);
  if (!design) return null;

  design.status = 'rejected';
  data.stats.totalRejected++;
  saveData(data);
  return design;
}

async function listApprovedDesign(designId) {
  const data = loadData();
  const design = data.designs.find(d => d.id === designId);
  if (!design) throw new Error('Design not found');
  if (design.status !== 'approved') throw new Error('Design must be approved before listing');

  const trend = data.trends.find(t => t.id === design.trendId) || { title: design.phrase, aiAnalysis: {} };
  const settings = data.settings || DEFAULT_SETTINGS;

  const shopifyResult = await listDesignToShopify(design, trend, settings);

  design.status = 'listed';
  design.listedAt = new Date().toISOString();
  design.shopifyProductId = shopifyResult.shopifyProductId;
  design.shopifyProductUrl = shopifyResult.shopifyProductUrl;
  data.stats.totalListed++;
  saveData(data);

  return design;
}

