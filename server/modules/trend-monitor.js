async function sendTrendAlerts(trends, settings) {
  const trendSummary = trends.map(t =>
    `[${t.score}] ${t.title} (${t.source})`
  ).join('\n');

  // SMS
  if (settings.notifySms) {
    try {
      const sms = require('../sms');
      if (sms.isConfigured()) {
        const body = `[TrendMonitor] ${trends.length} hot trend(s)!\n\n${trendSummary.slice(0, 300)}`;
        await sms.sendBulkSms({
          to: settings.smsRecipients,
          body
        });
        console.log(`[TrendMonitor] SMS alert sent to ${settings.smsRecipients.length} recipient(s)`);
      }
    } catch (err) {
      console.error('[TrendMonitor] SMS alert error:', err.message);
    }
  }

  // Email
  if (settings.notifyEmail && settings.emailRecipients?.length) {
    try {
      const { sendOrdersEmail } = require('../mailer');
      const html = buildTrendAlertEmail(trends);
      for (const email of settings.emailRecipients) {
        await sendOrdersEmail({
          to: email,
          subject: `[TrendMonitor] ${trends.length} Hot Trend(s) Found`,
          text: trendSummary,
          html
        });
      }
      console.log(`[TrendMonitor] Email alert sent to ${settings.emailRecipients.length} recipient(s)`);
    } catch (err) {
      console.error('[TrendMonitor] Email alert error:', err.message);
    }
  }
}

function buildTrendAlertEmail(trends) {
  const rows = trends.map(t => {
    const color = t.score >= 90 ? '#22c55e' : t.score >= 80 ? '#f59e0b' : '#3b82f6';
    const phrases = (t.aiAnalysis?.suggestedPhrases || []).slice(0, 2).join(' | ');
    return `
      <div style="background:#f8fafc;padding:15px;border-radius:8px;margin:10px 0;border-left:4px solid ${color};">
        <strong style="font-size:1.1em;">${t.title}</strong><br>
        <span style="color:#64748b;">Score: ${t.score} | Source: ${t.source}${t.subreddit ? ` (r/${t.subreddit})` : ''} | Audience: ${t.aiAnalysis?.targetAudience || 'all'}</span><br>
        ${phrases ? `<em style="color:#475569;">Phrases: ${phrases}</em>` : ''}
      </div>`;
  }).join('');

  return `
    <div style="font-family:Arial,sans-serif;max-width:600px;margin:0 auto;">
      <h2 style="color:#2563eb;">Trending Now</h2>
      <p>${trends.length} trend(s) scored above your alert threshold:</p>
      ${rows}
      <p style="margin-top:20px;">
        <a href="#" style="display:inline-block;background:#2563eb;color:white;padding:12px 24px;text-decoration:none;border-radius:6px;">Open Print Station to Review</a>
      </p>
      <p style="color:#94a3b8;font-size:0.85em;">Sent by Trend Monitor | BlueRidgeCustomCo</p>
    </div>`.trim();
}

