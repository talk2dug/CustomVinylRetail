// GOOGLE TRENDS CLIENT (RSS feed — works from datacenter IPs)
// =============================================================================

function parseRssFeed(xml) {
  const items = [];
  const itemRegex = /<item>([\s\S]*?)<\/item>/g;
  let match;
  while ((match = itemRegex.exec(xml)) !== null) {
    const block = match[1];
    const get = (tag) => {
      const m = block.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)<\\/${tag}>`));
      return m ? m[1].replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').trim() : '';
    };
    items.push({
      title: get('title'),
      link: get('link'),
      description: get('description'),
      pubDate: get('pubDate'),
      traffic: get('ht:approx_traffic') || get('ht:picture_source')
    });
  }
  return items;
}

async function fetchGoogleTrends(geo = 'US') {
  const trends = [];

  try {
    const url = `https://trends.google.com/trending/rss?geo=${encodeURIComponent(geo)}`;
    const xml = await httpGet(url);

    if (typeof xml !== 'string' || !xml.includes('<item>')) {
      console.error('[TrendMonitor] Google Trends RSS: unexpected response');
      return trends;
    }

    const items = parseRssFeed(xml);

    for (const item of items) {
      const title = item.title;
      if (!title) continue;

      // Parse related news from description HTML
      const newsMatch = (item.description || '').match(/<a[^>]+href="([^"]+)"[^>]*>([^<]+)<\/a>/);
      const newsTitle = newsMatch ? newsMatch[2] : '';
      const newsUrl = newsMatch ? newsMatch[1] : '';

      trends.push({
        id: `google_${crypto.createHash('md5').update(title).digest('hex').slice(0, 12)}`,
        source: 'google_trends',
        sourceId: title,
        title: title,
        snippet: newsTitle.slice(0, 200),
        url: newsUrl || `https://trends.google.com/trends/explore?q=${encodeURIComponent(title)}&geo=${geo}`,
        subreddit: null,
        upvotes: null,
        comments: null,
        searchVolume: item.traffic || null,
        relatedQueries: []
      });
    }
  } catch (err) {
    console.error('[TrendMonitor] Google Trends error:', err.message);
  }

  return trends;
}

