function handleTrendMonitorRoute(req, res, parsedUrl, sendJson, db) {
  const pathname = parsedUrl.pathname;

  // GET /api/trends/ — list current trends
  if ((pathname === '/api/trends/' || pathname === '/api/trends') && req.method === 'GET') {
    const data = loadData();
    const status = parsedUrl.searchParams?.get('status');
    let trends = data.trends || [];
    if (status && status !== 'all') {
      trends = trends.filter(t => t.status === status);
    }
    trends.sort((a, b) => (b.score || 0) - (a.score || 0));
    sendJson(res, {
      trends,
      lastScanAt: data.lastScanAt,
      totalCount: trends.length
    });
    return true;
  }

  // GET /api/trends/designs — list designs
  if (pathname === '/api/trends/designs' && req.method === 'GET') {
    const data = loadData();
    const status = parsedUrl.searchParams?.get('status');
    let designs = data.designs || [];
    if (status && status !== 'all') {
      designs = designs.filter(d => d.status === status);
    }
    designs.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
    sendJson(res, { designs, totalCount: designs.length });
    return true;
  }

  // GET /api/trends/settings — get settings
  if (pathname === '/api/trends/settings' && req.method === 'GET') {
    const data = loadData();
    sendJson(res, data.settings || DEFAULT_SETTINGS);
    return true;
  }

  // PUT /api/trends/settings — update settings
  if (pathname === '/api/trends/settings' && req.method === 'PUT') {
    let body = '';
    req.on('data', chunk => body += chunk);
    req.on('end', () => {
      try {
        const updates = JSON.parse(body);
        const data = loadData();
        data.settings = { ...data.settings, ...updates };
        saveData(data);
        sendJson(res, { ok: true, settings: data.settings });
      } catch (err) {
        sendJson(res, { error: err.message }, 400);
      }
    });
    return true;
  }

  // GET /api/trends/stats — aggregate stats
  if (pathname === '/api/trends/stats' && req.method === 'GET') {
    const data = loadData();
    const pendingDesigns = (data.designs || []).filter(d => d.status === 'pending').length;
    const approvedDesigns = (data.designs || []).filter(d => d.status === 'approved').length;
    sendJson(res, {
      ...data.stats,
      lastScanAt: data.lastScanAt,
      scanCount: data.scanCount,
      activeTrends: (data.trends || []).length,
      pendingDesigns,
      approvedDesigns,
      scanRunning: _scanRunning
    });
    return true;
  }

  // GET /api/trends/history — archived trends
  if (pathname === '/api/trends/history' && req.method === 'GET') {
    const history = loadHistory();
    const limit = parseInt(parsedUrl.searchParams?.get('limit') || '50', 10);
    sendJson(res, {
      trends: (history.archivedTrends || []).slice(-limit).reverse(),
      designs: (history.archivedDesigns || []).slice(-limit).reverse()
    });
    return true;
  }

  // POST /api/trends/scan — trigger manual scan
  if (pathname === '/api/trends/scan' && req.method === 'POST') {
    if (_scanRunning) {
      sendJson(res, { ok: false, message: 'Scan already in progress' });
      return true;
    }
    const data = loadData();
    const settings = data.settings || DEFAULT_SETTINGS;
    // Run async — respond immediately
    runTrendScan(settings).then(results => {
      console.log(`[TrendMonitor] Manual scan completed: ${results.length} trends`);
    }).catch(err => {
      console.error('[TrendMonitor] Manual scan failed:', err.message);
    });
    sendJson(res, { ok: true, message: 'Scan started' });
    return true;
  }

  // POST /api/trends/designs/:id/approve
  const approveMatch = pathname.match(/^\/api\/trends\/designs\/([^/]+)\/approve$/);
  if (approveMatch && req.method === 'POST') {
    const design = approveDesign(approveMatch[1]);
    if (design) {
      sendJson(res, { ok: true, design });
    } else {
      sendJson(res, { error: 'Design not found' }, 404);
    }
    return true;
  }

  // POST /api/trends/designs/:id/reject
  const rejectMatch = pathname.match(/^\/api\/trends\/designs\/([^/]+)\/reject$/);
  if (rejectMatch && req.method === 'POST') {
    const design = rejectDesign(rejectMatch[1]);
    if (design) {
      sendJson(res, { ok: true, design });
    } else {
      sendJson(res, { error: 'Design not found' }, 404);
    }
    return true;
  }

  // POST /api/trends/designs/:id/regenerate
  const regenMatch = pathname.match(/^\/api\/trends\/designs\/([^/]+)\/regenerate$/);
  if (regenMatch && req.method === 'POST') {
    const data = loadData();
    const design = data.designs.find(d => d.id === regenMatch[1]);
    if (!design) {
      sendJson(res, { error: 'Design not found' }, 404);
      return true;
    }
    const trend = data.trends.find(t => t.id === design.trendId);
    if (!trend) {
      sendJson(res, { error: 'Associated trend not found' }, 404);
      return true;
    }
    // Run async
    generateDesignForTrend(trend, data.settings || DEFAULT_SETTINGS).then(newDesigns => {
      const d = loadData();
      // Mark old design as rejected
      const old = d.designs.find(dd => dd.id === design.id);
      if (old) old.status = 'rejected';
      d.designs.push(...newDesigns);
      d.stats.totalDesignsGenerated += newDesigns.length;
      saveData(d);
      console.log(`[TrendMonitor] Regenerated ${newDesigns.length} design(s) for trend ${trend.id}`);
    }).catch(err => {
      console.error('[TrendMonitor] Regeneration failed:', err.message);
    });
    sendJson(res, { ok: true, message: 'Regeneration started' });
    return true;
  }

  // POST /api/trends/designs/:id/list — list to Shopify
  const listMatch = pathname.match(/^\/api\/trends\/designs\/([^/]+)\/list$/);
  if (listMatch && req.method === 'POST') {
    const designId = listMatch[1];
    listApprovedDesign(designId).then(design => {
      console.log(`[TrendMonitor] Design ${designId} listed to Shopify: ${design.shopifyProductId}`);
    }).catch(err => {
      console.error(`[TrendMonitor] Listing failed for ${designId}:`, err.message);
    });
    sendJson(res, { ok: true, message: 'Listing to Shopify started' });
    return true;
  }

  // DELETE /api/trends/:id — dismiss/archive a trend
  const deleteMatch = pathname.match(/^\/api\/trends\/([^/]+)$/);
  if (deleteMatch && req.method === 'DELETE') {
    const archived = archiveTrend(deleteMatch[1]);
    sendJson(res, { ok: archived, message: archived ? 'Trend archived' : 'Trend not found' });
    return true;
  }

  return false;
}

