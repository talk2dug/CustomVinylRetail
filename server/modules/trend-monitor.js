// CONTENT FILTER
// =============================================================================

const BLOCKED_PATTERNS = [
  /sexual\s*assault/i, /rape\s*joke/i, /non-?consensual/i,
  /child\s*(abuse|exploitation)/i, /pedophil/i
];

function passesContentFilter(text, settings) {
  const combined = String(text || '');
  for (const pattern of BLOCKED_PATTERNS) {
    if (pattern.test(combined)) return false;
  }
  return true;
}

