function parseAtomFeed(xml) {
  // Lightweight Atom XML parser for Reddit RSS
  const entries = [];
  const entryRegex = /<entry>([\s\S]*?)<\/entry>/g;
  let match;
  while ((match = entryRegex.exec(xml)) !== null) {
    const block = match[1];
    const get = (tag) => {
      const m = block.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)<\\/${tag}>`));
      return m ? m[1].replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#39;/g, "'").replace(/&quot;/g, '"').trim() : '';
    };
    const linkMatch = block.match(/<link[^>]+href="([^"]+)"/);
    const idMatch = block.match(/<id>([^<]*)<\/id>/);

    entries.push({
      title: get('title'),
      link: linkMatch ? linkMatch[1] : '',
      content: get('content'),
      id: idMatch ? idMatch[1] : '',
      updated: get('updated'),
      category: (block.match(/<category[^>]+term="([^"]+)"/) || [])[1] || ''
    });
  }
  return entries;
}

async function fetchRedditTrends(subreddits, limit = 10) {
  const trends = [];
  const seen = new Set();

  for (const sub of subreddits) {
    try {
      const url = `https://www.reddit.com/r/${encodeURIComponent(sub)}/hot.rss?limit=${limit}`;
      const xml = await httpGet(url);

      if (typeof xml !== 'string' || !xml.includes('<entry>')) continue;

      const entries = parseAtomFeed(xml);

      for (const entry of entries) {
        if (!entry.title) continue;

        // Extract post ID from link or id field
        const idMatch = (entry.link || entry.id || '').match(/comments\/([a-z0-9]+)/);
        const postId = idMatch ? idMatch[1] : crypto.createHash('md5').update(entry.title).digest('hex').slice(0, 10);

        if (seen.has(postId)) continue;
        seen.add(postId);

        // Try to extract upvote count from content HTML (Reddit includes it in some feeds)
        const scoreMatch = (entry.content || '').match(/(\d[\d,]+)\s*(?:points?|upvotes?)/i);
        const upvotes = scoreMatch ? parseInt(scoreMatch[1].replace(/,/g, ''), 10) : null;

        trends.push({
          id: `reddit_${postId}`,
          source: 'reddit',
          sourceId: postId,
          title: entry.title.slice(0, 300),
          snippet: (entry.content || '').replace(/<[^>]+>/g, '').slice(0, 200),
          url: entry.link || `https://reddit.com/r/${sub}`,
          subreddit: entry.category || sub,
          upvotes: upvotes,
          comments: null,
          searchVolume: null,
          relatedQueries: [],
          createdUtc: entry.updated ? Math.floor(new Date(entry.updated).getTime() / 1000) : null
        });
      }

      // Rate limit: 1 req/sec
      await new Promise(r => setTimeout(r, 1200));
    } catch (err) {
      console.error(`[TrendMonitor] Reddit RSS error for r/${sub}:`, err.message);
    }
  }

  return trends;
}

